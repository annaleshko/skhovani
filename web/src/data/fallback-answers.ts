export function findCuratedDefaultAnswer(
  artworkId: number,
  question: string,
): FallbackAnswer | null {
  const list = FALLBACK_ANSWERS[artworkId] ?? [];
  const q = norm(question);
  if (!q) return null;
  const exact = list.find((f) => norm(f.question) === q);
  if (exact?.answer) return exact;
  // Soft match: typed/tapped default with minor punctuation drift
  const soft = list.find((f) => {
    const fq = norm(f.question);
    return (
      Boolean(f.answer) &&
      (q.includes(fq.slice(0, 22)) || fq.includes(q.slice(0, 22)))
    );
  });
  return soft ?? null;
}

export function findFallbackAnswer(
  artworkId: number,
  question: string,
): FallbackAnswer {
  const curated = findCuratedDefaultAnswer(artworkId, question);
  if (curated) return curated;

  if (isLocationTrapQuestion(question)) {
    const a = getArtwork(artworkId);
    if (artworkId === 1 || a?.slug === "velykodnia-zautrenia") {
      return {
        question,
        answer:
          "Окупанти вивезли її з музею; за паспортом, обидві версії зараз у Росії. Точного місця я не знаю і не вгадую.",
        sourceIds: ["s1", "s8"],
        reviewed: false,
      };
    }
    if (a?.status === "stolen") {
      return {
        question,
        answer: GUIDE_SAFE_STOLEN,
        sourceIds: a.sources[0] ? [a.sources[0].id] : [],
        reviewed: false,
      };
    }
    if (a?.status === "shelter") {
      return {
        question,
        answer: GUIDE_SAFE_SHELTER,
        sourceIds: [],
        reviewed: false,
      };
    }
    if (a?.status === "saved") {
      return {
        question,
        answer: GUIDE_SAFE_SAVED,
        sourceIds: [],
        reviewed: false,
      };
    }
    return {
      question,
      answer: "Про точне місце в моїх джерелах даних немає.",
      sourceIds: [],
      reviewed: false,
    };
  }

  const list = FALLBACK_ANSWERS[artworkId] ?? [];
  const q = norm(question);
  const partial = list.find(
    (f) =>
      q.includes(norm(f.question).slice(0, 18)) ||
      norm(f.question).includes(q.slice(0, 18)),
  );
  if (partial?.answer) return partial;

  const art = getArtwork(artworkId);

  // Broader topic questions → context-bank style (esp. Melitopol gold).
  if (
    artworkId === 3 &&
    /(ще|інш|крім|взагалі).{0,24}(ск[іi]ф|золот)|ск[іi]ф.{0,24}(ще|інш)/i.test(
      q,
    )
  ) {
    const broader = FALLBACK_ANSWERS[3]?.find((f) =>
      /Чи є ще скіфське/.test(f.question),
    );
    if (broader) return { ...broader, question };
  }

  const outOfPassport =
    /цін[аи]|кошт|вартіст|аукціон|символізу|що означає|навіщо червон/i.test(q);
  if (outOfPassport) {
    const offer =
      art?.chat.defaultQuestions[0] ??
      "Спитай про сюжет, автора чи долю твору.";
    return {
      question,
      answer: `Про це в моїх джерелах даних немає. Можу розказати: «${offer}»`,
      sourceIds: [],
      reviewed: false,
    };
  }

  if (art) {
    const about = art.tabs.about[0];
    if (
      about &&
      /сюжет|що (там|відбува|зображ)|про (що|полотно)/i.test(q)
    ) {
      return {
        question,
        answer: about,
        sourceIds: art.sources[0] ? [art.sources[0].id] : [],
        reviewed: false,
      };
    }
    const zone = art.touchZones.zones.find((z) =>
      q.includes(z.title.toLowerCase()),
    );
    if (zone) {
      return {
        question,
        answer: zone.text,
        sourceIds: [],
        reviewed: false,
      };
    }
  }

  return {
    question,
    answer:
      "Про це в моїх джерелах даних немає. Спробуй спитати про сюжет, автора чи долю твору — можу відповісти з паспорта.",
    sourceIds: [],
    reviewed: false,
  };
}

/** Passport paragraphs likely relevant to a free-form question (for retry). */
export function passportSnippetsForQuestion(
  artworkId: number,
  question: string,
): string[] {
  const art = getArtwork(artworkId);
  if (!art) return [];
  const q = question.toLowerCase();
  const pool = [
    ...art.tabs.history,
    ...art.tabs.about,
    ...art.tabs.author,
  ];
  const keywords = q
    .split(/[^\p{L}\p{N}]+/u)
    .map((w) => w.trim())
    .filter((w) => w.length >= 4);
  const hits = pool.filter((p) => {
    const low = p.toLowerCase();
    return keywords.some((w) => low.includes(w));
  });
  return (hits.length ? hits : pool.slice(0, 2)).slice(0, 4);
}

export function listAllFallbacks(): FallbackAnswer[] {
  return Object.values(FALLBACK_ANSWERS).flat();
}
